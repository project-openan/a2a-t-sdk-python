"""Deterministic free-text plan for a terse pure-A2A confirmation question.

The real vendor's standard-A2A front end does not render the business issue: every negotiation
round is the same sentence, ``Not feasible, please confirm``. An automatic client must still answer
with a concrete value, otherwise the vendor has nothing to execute. This module owns that value:

* the operator's own request supplies the region, the time window and the rate;
* a long outage (strictly more than four hours) with a rate above the vendor's 2 Mbps floor gets a
  deterministic concession ladder 10/20 → 5 → 2 Mbps;
* a request that names a bitrate quality instead of a rate (720p/1080p/4K) uses the protocol's
  documented terminology mapping;
* a complete request is restated, never answered with a bare "Accepted".

The plan is prose, because standard A2A has no structured negotiation channel. It is generated by
code, not by the model, so it is auditable and unit-testable; the model only handles the questions
whose value cannot be derived deterministically.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Final

from protocol.client_policy import ClientPolicy
from protocol.grounding import server_target_rates
from shared import energy_rules
from shared.models import NegotiationProposeView

#: The vendor's feasibility floor: a rate at or below this is feasible for a long outage.
FEASIBILITY_FLOOR_MBPS: Final[float] = energy_rules.FEASIBILITY_RATE_MBPS

#: Concession ladder. The OSP corpus records 10 → 5 → 2 for a ten-hour outage.
_CONCESSION_RATES: Final[tuple[float, ...]] = (10.0, 5.0, 2.0)

#: One ``Mbps`` value in the operator's request.
_RATE: Final[re.Pattern[str]] = re.compile(r"([0-9]+(?:\.[0-9]+)?)\s*(?:Mbps|Mbit/s|Mbit)", re.IGNORECASE)

#: A rate written without its unit in a rate-quality sentence ("Ensure the UX target is at least
#: 10", "Set the DL rate floor to 10", "SLA 10"). The OSP corpus writes it both ways.
_BARE_RATE: Final[re.Pattern[str]] = re.compile(
    r"(?:at\s+least|no\s+less\s+than|ux\s+target|user\s+experience\s+target|dl\s+rate\s+floor|"
    r"rate\s+floor|sla|guaranteed\s+(?:throughput|rate)(?:\s+target)?)"
    r"[^0-9]{0,24}(\d+(?:\.\d+)?)(?!\s*(?:Mbps|Mbit/s|Mbit))",
    re.IGNORECASE,
)

#: Bitrate-quality terminology from the protocol's Terminology Explanation section.
_TERMINOLOGY_RATES: Final[tuple[tuple[re.Pattern[str], float], ...]] = (
    (re.compile(r"(?<!\d)720p\b", re.IGNORECASE), 2.0),
    (re.compile(r"(?<!\d)1080p\b", re.IGNORECASE), 10.0),
    (re.compile(r"(?<!\d)4k\b", re.IGNORECASE), 20.0),
)

#: One ``HH:MM`` clock pair written with any of the request separators.
_WINDOW: Final[re.Pattern[str]] = re.compile(
    r"(\d{1,2}:\d{2})(?::\d{2})?\s*(?:[~\-–—]|to|until|至)\s*(\d{1,2}:\d{2})(?::\d{2})?",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class PureConcession:
    """One concrete free-text answer to a plan-less confirmation question.

    Attributes:
        text: The answer to send.
        rationale: Why the client chose that value, for the trace and the log.
    """

    text: str
    rationale: str


def plan_pure_answer(
    request_text: str,
    propose: NegotiationProposeView,
    policy: ClientPolicy,
) -> PureConcession | None:
    """Return a concrete free-text plan for one terse confirmation question.

    Only a question that names no alternative is handled here: when the vendor states its revised
    plan, a plain affirmation is the complete answer and the model path owns it. ``None`` means the
    request carries no value this module can derive, so the caller falls back to the model or to
    the operator.
    """
    if propose.kind not in ("feasibility", "target"):
        return None
    if server_target_rates(propose):
        return None
    explicit = tuple(float(match.group(1)) for match in _RATE.finditer(request_text))
    floor = _policy_floor(policy)
    outage_hours = energy_rules.outage_duration_hours(request_text)
    long_outage = outage_hours is not None and outage_hours > energy_rules.FEASIBILITY_OUTAGE_HOURS
    if explicit:
        rate = max(explicit)
        if not (long_outage and rate > FEASIBILITY_FLOOR_MBPS):
            # The request already states the rate and the vendor is not objecting to it. The
            # question is about another field (RAT, mode, gain, sites); the model can name the
            # value the request states, while restating the rate would answer the wrong question.
            return None
        next_rate = _concede(rate, floor)
        if next_rate is None:
            return None
        return PureConcession(
            text=f"Lower the guaranteed throughput target to {next_rate:g}Mbps during the outage.",
            rationale=(
                f"the {outage_hours:g}-hour outage with {rate:g}Mbps exceeds the feasibility limit; "
                f"the client concedes to {next_rate:g}Mbps"
            ),
        )
    derived = _derived_rate(request_text)
    if derived is None:
        return None
    if long_outage and derived > FEASIBILITY_FLOOR_MBPS:
        next_rate = _concede(derived, floor)
        if next_rate is None:
            return None
        return PureConcession(
            text=f"Lower the guaranteed throughput target to {next_rate:g}Mbps during the outage.",
            rationale=(
                f"the {outage_hours:g}-hour outage with {derived:g}Mbps exceeds the feasibility "
                f"limit; the client concedes to {next_rate:g}Mbps"
            ),
        )
    window = _window_text(request_text)
    if window is not None:
        return PureConcession(
            text=f"Set the guaranteed throughput targets: {window}→{derived:g}Mbps.",
            rationale=f"the request names no concrete rate; use the documented {derived:g}Mbps value",
        )
    return PureConcession(
        text=f"The guaranteed throughput target is {derived:g}Mbps.",
        rationale=f"the request names no concrete rate; use the documented {derived:g}Mbps value",
    )


def _derived_rate(request_text: str) -> float | None:
    """Return the rate a rate-quality sentence implies, or ``None`` when the request has none."""
    bare = _BARE_RATE.search(request_text)
    if bare is not None:
        return float(bare.group(1))
    for pattern, rate in _TERMINOLOGY_RATES:
        if pattern.search(request_text):
            return rate
    return None


def _policy_floor(policy: ClientPolicy) -> float | None:
    """Return the client's own floor, never below the vendor's feasibility floor."""
    floor = policy.min_throughput_mbps
    if floor is None:
        return None
    return max(float(floor), FEASIBILITY_FLOOR_MBPS)


def _concede(rate: float, floor: float | None) -> float | None:
    """Return the next rate on the concession ladder, or ``None`` when nothing is left to concede."""
    candidates = [value for value in _CONCESSION_RATES if value < rate]
    if not candidates:
        return None
    next_rate = max(candidates)
    if floor is not None and next_rate < floor:
        # Conceding below the client floor is not allowed, and offering a rate above the ladder
        # would just be rejected again. The caller relays the question instead.
        return None
    return next_rate


def _window_text(request_text: str) -> str | None:
    """Return the request's first time window as ``HH:MM-HH:MM``, or ``None``."""
    match = _WINDOW.search(request_text)
    if match is None:
        return None
    return f"{_clock(match.group(1))}-{_clock(match.group(2))}"


def _clock(value: str) -> str:
    """Normalize ``H:MM`` to ``HH:MM``."""
    hour, minute = value.split(":", 1)
    return f"{int(hour):02d}:{minute}"


__all__ = ["FEASIBILITY_FLOOR_MBPS", "PureConcession", "plan_pure_answer"]
