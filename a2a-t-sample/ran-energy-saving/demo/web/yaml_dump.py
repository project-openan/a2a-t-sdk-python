"""The YAML style the operator-facing exports share.

The annotation snippet and the review report are both read and edited by people. An indentless
sequence and a folded quoted scalar are valid YAML but make a multi-line negotiation message or a
nested evidence list unreadable, so both exports use this dumper.
"""

from __future__ import annotations

from collections.abc import Mapping
from typing import Final

import yaml

#: Comment line prepended to every export, naming its schema.
SCHEMA_HEADER: Final[str] = "# {schema} — generated by the OSP console.\n"


class BlockDumper(yaml.SafeDumper):
    """Dump sequences indented under their key and multiline text as literal blocks."""

    def increase_indent(
        self,
        flow: bool = False,
        indentless: bool = False,
    ) -> None:  # noqa: ARG002 - yaml API
        super().increase_indent(flow, False)


def _represent_text(dumper: yaml.SafeDumper, data: str) -> yaml.Node:
    """Emit a multiline string as a ``|`` block scalar, any other string as usual."""
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


BlockDumper.add_representer(str, _represent_text)


def dump_yaml(payload: Mapping[str, object], *, header: str = "") -> str:
    """Render one payload with the shared export style."""
    body = yaml.dump(
        dict(payload),
        Dumper=BlockDumper,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=1000,
    )
    return header + body


__all__ = ["BlockDumper", "SCHEMA_HEADER", "dump_yaml"]
