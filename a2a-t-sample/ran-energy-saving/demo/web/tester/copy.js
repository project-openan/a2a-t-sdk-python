export const COPY = { "zh-CN": ZH, "en-US": EN };

/** Return the copy table of one process language, falling back to the template language. */
export function copyFor(language) {
  return COPY[language] || ZH;
}

/** Fill ``{name}`` placeholders of one template; an unknown key stays visible. */
export function t(copy, key, params = {}) {
  const template = copy[key];
  if (template === undefined) return key;
  return String(template).replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}

/** Replace static shell copy from ``data-i18n``, ``data-i18n-title`` and ``data-i18n-placeholder``. */
export function applyDataI18n(root, copy) {
  for (const node of root.querySelectorAll("[data-i18n]")) {
    const value = copy[node.dataset.i18n];
    if (value !== undefined) node.textContent = value;
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    const value = copy[node.dataset.i18nTitle];
    if (value !== undefined) node.title = value;
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    const value = copy[node.dataset.i18nPlaceholder];
    if (value !== undefined) node.placeholder = value;
  }
}

/** The three fixed OSP validation labels, shown in English but never rewritten in the corpus. */
const VALIDATE_LABELS_EN = {
  "拦截": "blocked",
  "不拦截，携带术语上下文信息": "not blocked (terminology context carried)",
  "不拦截": "not blocked",
};

/** Map the fixed Chinese validation labels to English; every other value stays verbatim. */
export function localizeValidateLabel(copy, raw) {
  if (raw === null || raw === undefined || raw === "") return raw ?? "";
  if (copy.lang !== "en-US") return raw;
  return VALIDATE_LABELS_EN[raw] || raw;
}

