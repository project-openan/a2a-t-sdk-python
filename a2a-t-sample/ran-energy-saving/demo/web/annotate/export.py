"""Export formats of the annotation console.

The console never writes the corpus. In the yellow zone the case files are hot-replaced between
runs, so a direct write would be overwritten (or would silently diverge from the copy that is
actually being tested). The operator merges the exported values instead.

Two shapes cover both uses:

* :func:`payload` — the whole confirmed set as one ``osp-annotations/v1`` document, portable
  between environments.
* :func:`case_snippet` — the same values for one case, rendered at the nesting level of
  ``expect.protocols`` so they can be pasted into a case file after review.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from typing import Any, Final

import yaml
from eval.osp.catalog import OVERLAY_SCHEMA

from demo.web.yaml_dump import BlockDumper, dump_yaml

#: Format marker of the portable payload. It doubles as the catalog overlay schema: the exported
#: file can be dropped at ``eval/osp/expectations-overlay.yaml`` instead of being merged into the
#: hot-replaced case files.
SCHEMA: Final[str] = OVERLAY_SCHEMA


def payload_yaml(payload: Mapping[str, object]) -> str:
    """Render the whole confirmed set as YAML."""
    header = (
        f"# {SCHEMA} — generated by the expectation annotation console.\n"
        "# Drop this file next to the case directory (eval/osp/expectations-overlay.yaml) and the\n"
        "# catalog will merge it; the hot-replaced case files stay untouched.\n"
    )
    return dump_yaml(payload, header=header)


def case_entry(payload: Mapping[str, object], case_id: int) -> Mapping[str, object] | None:
    """Return one case's expectations of the payload, or ``None`` when it has none."""
    entries = payload.get("cases")
    if not isinstance(entries, list):
        return None
    for entry in entries:
        if isinstance(entry, Mapping) and entry.get("id") == case_id:
            return entry
    return None


def case_snippet(
    payload: Mapping[str, object],
    case_id: int,
    *,
    case_name: str = "",
) -> str:
    """Render one case's confirmed expectations as a paste-ready YAML fragment.

    The fragment is written at the ``expect.protocols`` nesting level: its keys are ``a2a-t`` and
    ``a2a``, so it is pasted two levels below ``expect:``. An empty fragment is a comment instead of
    an empty string, so the page can always show something to copy.
    """
    entry = case_entry(payload, case_id)
    title = f"# case {case_id}" + (f" · {case_name}" if case_name else "")
    if entry is None:
        return (
            f"{title}\n"
            "# 该用例没有已确认的期望；先在左侧采纳候选并确认。\n"
        )
    blocks: dict[str, Any] = {
        key: value for key, value in entry.items() if key != "id"
    }
    body = yaml.dump(
        blocks,
        Dumper=BlockDumper,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=1000,
    )
    indent = " " * 6
    rendered = "\n".join(f"{indent}{line}" if line.strip() else "" for line in body.splitlines())
    return (
        f"{title}\n"
        "# 首选放进 eval/osp/expectations-overlay.yaml 的该用例条目（不要改会被热更新替换的用例 YAML）。\n"
        f"{rendered}\n"
    )


def payload_json(payload: Mapping[str, object]) -> str:
    """Render the whole confirmed set as JSON (for a diff/merge workflow)."""
    return json.dumps(dict(payload), ensure_ascii=False, indent=2)


__all__ = ["SCHEMA", "case_entry", "case_snippet", "payload_json", "payload_yaml"]
