"""Export formats of the acceptance review console.

The review page never writes the corpus either: the yellow zone hot-replaces case files, and an
acceptance decision is not an expectation. Two artifacts leave the console:

* :func:`payload` — an ``osp-review/v1`` document carrying every protocol task's automatic verdict
  and human decision, portable across environments;
* :func:`report_markdown` — a deterministic acceptance report: summary, case matrix, defect list
  (with the reviewer's category and the failed dimensions), acknowledged deviations, and the units
  that still need a run or a re-confirmation.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from datetime import UTC, datetime
from typing import Final

from eval.osp.tracecheck import TRACE_REASONS, Fidelity, fidelity_summary

from demo.web.yaml_dump import dump_yaml

#: Format marker of the portable payload.
SCHEMA: Final[str] = "osp-review/v1"

_PROTOCOL_LABEL: Final[dict[str, str]] = {"a2a-t": "A2A-T", "a2a": "A2A"}
_STATUS_LABEL: Final[dict[str, str]] = {
    "pass": "通过",
    "fail": "失败",
    "partial": "部分可判",
    "recorded": "仅记录",
    "missing": "缺证据",
    "not_expected": "不适用",
    "not_applicable": "不适用",
    "stale": "需重跑",
    "not_run": "未跑",
}
_DECISION_LABEL: Final[dict[str, str]] = {
    "pending": "未审核",
    "accepted": "通过",
    "defect": "缺陷",
    "known_issue": "已知问题",
    "recheck": "待复核",
}
_CATEGORY_LABEL: Final[dict[str, str]] = {
    "sdk": "SDK",
    "vendor": "网管",
    "case": "用例",
    "env": "环境",
    "other": "其他",
    "": "—",
}


def build_payload(
    cases: Sequence[Mapping[str, object]],
    *,
    counts: Mapping[str, object],
    corpus_version: str,
) -> dict[str, object]:
    """Return the portable review payload."""
    return {
        "schema": SCHEMA,
        "generatedAt": datetime.now(UTC).isoformat(timespec="seconds"),
        "corpusVersion": corpus_version,
        "counts": dict(counts),
        "cases": [_case_entry(case) for case in cases],
    }


def payload_yaml(payload: Mapping[str, object]) -> str:
    """Render the review payload as YAML."""
    header = (
        f"# {SCHEMA} — generated by the acceptance review console.\n"
        "# Decisions and automatic verdicts; the corpus itself was not modified.\n"
    )
    return dump_yaml(payload, header=header)


def payload_json(payload: Mapping[str, object]) -> str:
    """Render the review payload as JSON."""
    return json.dumps(dict(payload), ensure_ascii=False, indent=2)


def report_markdown(
    payload: Mapping[str, object],
    *,
    window: Mapping[str, object] | None = None,
) -> str:
    """Render the deterministic acceptance report."""
    counts = payload.get("counts")
    statuses = counts.get("statuses") if isinstance(counts, Mapping) else {}
    decisions = counts.get("decisions") if isinstance(counts, Mapping) else {}
    lines: list[str] = [
        "# OSP 验收审核报告",
        "",
        f"- 生成时间：{payload.get('generatedAt')}",
        f"- 用例语料版本：`{payload.get('corpusVersion')}`",
    ]
    if window:
        lines.append(
            f"- 证据窗口：{window.get('windowStart') or '—'} → {window.get('windowEnd') or '—'}"
        )
    lines.extend(["", "## 0. 结论", ""])
    lines.append("| 自动判定 | 数量 |")
    lines.append("|---|---:|")
    for status in (
        "pass", "fail", "partial", "recorded", "missing",
        "stale", "not_run", "not_expected", "not_applicable",
    ):
        value = statuses.get(status) if isinstance(statuses, Mapping) else 0
        if value:
            lines.append(f"| {_STATUS_LABEL.get(status, status)} | {value} |")
    lines.extend(["", "| 审核结论 | 数量 |", "|---|---:|"])
    for status in ("pending", "accepted", "defect", "known_issue", "recheck"):
        value = decisions.get(status) if isinstance(decisions, Mapping) else 0
        lines.append(f"| {_DECISION_LABEL[status]} | {value or 0} |")

    raw_cases = payload.get("cases")
    entries = (
        [case for case in raw_cases if isinstance(case, Mapping)]
        if isinstance(raw_cases, list)
        else []
    )
    lines.extend(["", "## 1. 用例矩阵", ""])
    lines.append("| 编号 | 用例 | A2A-T 自动 | A2A-T 结论 | A2A 自动 | A2A 结论 |")
    lines.append("|---:|---|---|---|---|---|")
    for case in entries:
        protocols = case.get("protocols")
        tasks: Mapping[str, object] = protocols if isinstance(protocols, Mapping) else {}
        raw_a2a_t = tasks.get("a2a-t")
        raw_a2a = tasks.get("a2a")
        a2a_t: Mapping[str, object] = raw_a2a_t if isinstance(raw_a2a_t, Mapping) else {}
        a2a: Mapping[str, object] = raw_a2a if isinstance(raw_a2a, Mapping) else {}
        lines.append(
            "| {id} | {name} | {at} | {ad} | {pt} | {pd} |".format(
                id=case.get("id"),
                name=_escape(str(case.get("name") or "")),
                at=_STATUS_LABEL.get(str(a2a_t.get("status")), str(a2a_t.get("status"))),
                ad=_decision_label(a2a_t),
                pt=_STATUS_LABEL.get(str(a2a.get("status")), str(a2a.get("status"))),
                pd=_decision_label(a2a),
            )
        )

    defects = [
        (case, protocol, task)
        for case in entries
        for protocol, task in _tasks(case)
        if _decision_status(task) == "defect"
    ]
    lines.extend(["", "## 2. 缺陷清单", ""])
    if not defects:
        lines.append("（无）")
    by_category: dict[str, list[tuple[Mapping[str, object], str, Mapping[str, object]]]] = {}
    for case, protocol, task in defects:
        decision = task.get("decision")
        mapping = decision if isinstance(decision, Mapping) else {}
        by_category.setdefault(str(mapping.get("category") or ""), []).append(
            (case, protocol, task)
        )
    for category in ("sdk", "vendor", "case", "env", "other", ""):
        rows = by_category.get(category)
        if not rows:
            continue
        lines.extend(["", f"### {_CATEGORY_LABEL.get(category, category)}", ""])
        for case, protocol, task in rows:
            decision = task.get("decision")
            mapping = decision if isinstance(decision, Mapping) else {}
            lines.append(
                f"- `#{case.get('id')}` {case.get('name')} · {_PROTOCOL_LABEL.get(protocol, protocol)}"
                f" — {mapping.get('note') or '（无备注）'}"
            )
            for failure in _failures(task):
                lines.append(
                    f"  - {failure.get('dimension')}: "
                    f"{_STATUS_LABEL.get(str(failure.get('status')), str(failure.get('status')))}"
                    f" {failure.get('reason') or ''}".rstrip()
                )
            run_ids = _run_ids(mapping)
            if run_ids:
                lines.append(f"  - 证据：{', '.join(f'`{run_id}`' for run_id in run_ids)}")

    reason_counts: dict[str, int] = {}
    for case in entries:
        for _protocol, task in _tasks(case):
            reason = str(task.get("traceReason") or "")
            if reason in TRACE_REASONS:
                reason_counts[reason] = reason_counts.get(reason, 0) + 1
    if reason_counts:
        lines.extend(["", "## 2.1 轨迹判定原因", ""])
        lines.append("| 原因 | 数量 |")
        lines.append("|---|---:|")
        for code in TRACE_REASONS:
            if reason_counts.get(code):
                lines.append(f"| `{code}` | {reason_counts[code]} |")

    acknowledged = [
        (case, protocol, task)
        for case in entries
        for protocol, task in _tasks(case)
        if _decision_status(task) == "accepted" and _auto_status(task) != "pass"
    ]
    lines.extend(["", "## 3. 已认可偏差", ""])
    if not acknowledged:
        lines.append("（无）")
    for case, protocol, task in acknowledged:
        decision = task.get("decision")
        mapping = decision if isinstance(decision, Mapping) else {}
        lines.append(
            f"- `#{case.get('id')}` {case.get('name')} · {_PROTOCOL_LABEL.get(protocol, protocol)}"
            f" — 自动 {_STATUS_LABEL.get(_auto_status(task), _auto_status(task))}"
            f"；理由：{mapping.get('note') or '（无备注）'}"
        )

    pending = [
        (case, protocol, task)
        for case in entries
        for protocol, task in _tasks(case)
        if _decision_status(task) == "pending"
    ]
    lines.extend(["", "## 4. 待审核", ""])
    if not pending:
        lines.append("（无）")
    for case, protocol, task in pending:
        lines.append(
            f"- `#{case.get('id')}` {case.get('name')} · {_PROTOCOL_LABEL.get(protocol, protocol)}"
            f" — 自动 {_STATUS_LABEL.get(_auto_status(task), _auto_status(task))}"
        )

    notes = [
        (case, protocol, task)
        for case in entries
        for protocol, task in _tasks(case)
        if _decision_status(task) in ("known_issue", "recheck") or _decision_stale(task)
    ]
    lines.extend(["", "## 5. 已知问题 / 待复核", ""])
    if not notes:
        lines.append("（无）")
    for case, protocol, task in notes:
        decision = task.get("decision")
        mapping = decision if isinstance(decision, Mapping) else {}
        reasons: list[str] = [_DECISION_LABEL.get(str(mapping.get("status")), "")]
        if mapping.get("note"):
            reasons.append(str(mapping.get("note")))
        if mapping.get("staleReason"):
            reasons.append(str(mapping.get("staleReason")))
        if mapping.get("newEvidence"):
            reasons.append("有新证据")
        lines.append(
            f"- `#{case.get('id')}` {case.get('name')} · {_PROTOCOL_LABEL.get(protocol, protocol)}"
            f" — {'；'.join(reason for reason in reasons if reason)}"
        )
    _append_fidelity(lines, entries, key="taskT", summary_key="fidelity",
                     title="附录 A：Task-T 判定与下发差异")
    _append_fidelity(lines, entries, key="intent", summary_key="corroboration",
                     title="附录 B：意图 corroboration 漂移")
    lines.append("")
    return "\n".join(lines)


def _append_fidelity(
    lines: list[str],
    entries: Sequence[Mapping[str, object]],
    *,
    key: str,
    summary_key: str,
    title: str,
) -> None:
    """Append one failing-comparison appendix, or nothing when every target agrees."""
    rows: list[tuple[Mapping[str, object], str, Mapping[str, object]]] = []
    for case in entries:
        for protocol, task in _tasks(case):
            block = task.get(key)
            mapping = block if isinstance(block, Mapping) else {}
            summary = mapping.get(summary_key)
            summary_map = summary if isinstance(summary, Mapping) else {}
            if not summary_map.get("comparable") or summary_map.get("equal"):
                continue
            rows.append((case, protocol, summary_map))
    if not rows:
        return
    lines.extend(["", f"## {title}", ""])
    for case, protocol, summary_map in rows:
        truncated = "（导出文本已截断）" if summary_map.get("truncated") else ""
        lines.append(
            f"- `#{case.get('id')}` {case.get('name')} · {_PROTOCOL_LABEL.get(protocol, protocol)}"
            f" — {summary_map.get('differenceCount')} 处{truncated}"
        )
        differences = summary_map.get("differences")
        for diff in differences if isinstance(differences, list) else ():
            if not isinstance(diff, Mapping):
                continue
            lines.append(
                f"  - {diff.get('path')}: {diff.get('verdict') or diff.get('status')}"
            )


def _case_entry(case: Mapping[str, object]) -> dict[str, object]:
    """Render one case row of the portable payload."""
    protocols: dict[str, object] = {}
    rows = case.get("protocols")
    for task in rows if isinstance(rows, list) else ():
        if not isinstance(task, Mapping):
            continue
        protocol = str(task.get("protocol") or "")
        decision = task.get("decision")
        mapping = decision if isinstance(decision, Mapping) else {}
        detail = task.get("exportDetail")
        detail_map = detail if isinstance(detail, Mapping) else {}
        protocols[protocol] = {
            "status": str(task.get("status") or ""),
            "dimensions": {
                str(row.get("dimension")): str(row.get("status"))
                for row in task.get("dimensions") or ()
                if isinstance(row, Mapping)
            },
            "observations": task.get("observations"),
            "observedAt": task.get("observedAt"),
            "model": task.get("model"),
            "decisionMode": task.get("decisionMode"),
            "nms": task.get("nms"),
            "inputChanged": task.get("inputChanged"),
            "decision": {
                "status": str(mapping.get("status") or "pending"),
                "category": str(mapping.get("category") or ""),
                "note": str(mapping.get("note") or ""),
                "reviewer": str(mapping.get("reviewer") or ""),
                "confirmedAt": str(mapping.get("confirmedAt") or ""),
                "evidence": mapping.get("evidence") or {},
                "stale": bool(mapping.get("stale")),
                "staleReason": str(mapping.get("staleReason") or ""),
                "newEvidence": bool(mapping.get("newEvidence")),
            },
            "failures": list(task.get("failures") or ()),
            "traceReason": str(task.get("traceReason") or ""),
            "taskT": _task_t_entry(detail_map),
            "intent": _intent_entry(detail_map),
            "requests": _requests_entry(task.get("exportRequests")),
            "trace": _trace_entry(detail_map),
        }
    return {
        "id": case.get("caseId"),
        "name": case.get("caseName"),
        "operation": case.get("operation"),
        "blocked": case.get("blocked"),
        "protocols": protocols,
    }


def _task_t_entry(detail: Mapping[str, object]) -> dict[str, object]:
    """Return the Task-T block of one protocol task, with the compact fidelity summary."""
    block = detail.get("taskT")
    task_t = block if isinstance(block, Mapping) else {}
    return {
        "expected": task_t.get("expected"),
        "judged": task_t.get("judged"),
        "dispatched": task_t.get("dispatched"),
        "dispatchedTruncated": bool(task_t.get("dispatchedTruncated")),
        "fidelity": _fidelity_entry(task_t.get("fidelity")),
    }


def _intent_entry(detail: Mapping[str, object]) -> dict[str, object]:
    """Return the intent block of one protocol task; the server reading stays the oracle."""
    block = detail.get("intent")
    intent = block if isinstance(block, Mapping) else {}
    return {
        "expected": intent.get("expected"),
        "server": intent.get("server"),
        "sdk": intent.get("sdk"),
        "sourceOfTruth": "server",
        "corroboration": _fidelity_entry(intent.get("corroboration")),
    }


def _requests_entry(value: object) -> dict[str, object]:
    """Return the three request sources and where each came from."""
    block = value if isinstance(value, Mapping) else {}
    return {
        "original": block.get("original"),
        "originalSource": block.get("originalSource"),
        "intercepted": block.get("intercepted"),
        "followup": block.get("followup"),
        "dispatched": block.get("dispatched"),
        "dispatchedSource": block.get("dispatchedSource"),
    }


def _trace_entry(detail: Mapping[str, object]) -> dict[str, object]:
    """Return the trace summary and the process-point table of one round."""
    block = detail.get("trace")
    trace = block if isinstance(block, Mapping) else {}
    points = trace.get("points")
    return {
        "present": bool(trace.get("present")),
        "traceId": trace.get("traceId"),
        "fetchedAt": trace.get("fetchedAt"),
        "exportState": trace.get("exportState"),
        "frames": trace.get("frames") if isinstance(trace.get("frames"), Mapping) else {},
        "attribution": trace.get("attribution")
        if isinstance(trace.get("attribution"), Mapping)
        else {},
        "points": [
            {
                "id": row.get("point"),
                "label": row.get("label"),
                "expected": row.get("expected"),
                "observed": row.get("observed"),
                "ok": bool(row.get("ok")),
            }
            for row in points
            if isinstance(row, Mapping)
        ]
        if isinstance(points, list)
        else [],
    }


def _fidelity_entry(value: object) -> dict[str, object]:
    """Return one comparison in its compact export form (failing rows only)."""
    block = value if isinstance(value, Mapping) else {}
    rows = block.get("rows")
    fidelity = Fidelity(
        comparable=bool(block.get("comparable")),
        equal=bool(block.get("equal")),
        rows=tuple(row for row in rows if isinstance(row, Mapping))
        if isinstance(rows, list)
        else (),
        truncated=bool(block.get("truncated")),
    )
    return fidelity_summary(fidelity)


def _tasks(
    case: Mapping[str, object],
) -> list[tuple[str, Mapping[str, object]]]:
    """Return the protocol tasks of one payload case (the payload keys them by protocol)."""
    protocols = case.get("protocols")
    if isinstance(protocols, Mapping):
        return [
            (str(protocol), task)
            for protocol, task in protocols.items()
            if isinstance(task, Mapping)
        ]
    tasks: list[tuple[str, Mapping[str, object]]] = []
    for task in protocols if isinstance(protocols, list) else ():
        if isinstance(task, Mapping):
            tasks.append((str(task.get("protocol") or ""), task))
    return tasks


def _decision_status(task: Mapping[str, object]) -> str:
    decision = task.get("decision")
    mapping = decision if isinstance(decision, Mapping) else {}
    return str(mapping.get("status") or "pending")


def _auto_status(task: Mapping[str, object]) -> str:
    return str(task.get("status") or "not_run")


def _decision_stale(task: Mapping[str, object]) -> bool:
    decision = task.get("decision")
    mapping = decision if isinstance(decision, Mapping) else {}
    return bool(mapping.get("stale") or mapping.get("newEvidence"))


def _decision_label(task: Mapping[str, object]) -> str:
    decision = task.get("decision")
    mapping = decision if isinstance(decision, Mapping) else {}
    status = str(mapping.get("status") or "pending")
    label = _DECISION_LABEL.get(status, status)
    if mapping.get("stale") or mapping.get("newEvidence"):
        return f"{label}（待复核）"
    return label


def _failures(task: Mapping[str, object]) -> list[Mapping[str, object]]:
    rows = task.get("failures")
    return [row for row in rows if isinstance(row, Mapping)] if isinstance(rows, list) else []


def _run_ids(decision: Mapping[str, object]) -> list[str]:
    evidence = decision.get("evidence")
    run_ids = evidence.get("runIds") if isinstance(evidence, Mapping) else None
    return [str(run_id) for run_id in run_ids if run_id] if isinstance(run_ids, list) else []


def _escape(text: str) -> str:
    """Escape the characters that would break a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


